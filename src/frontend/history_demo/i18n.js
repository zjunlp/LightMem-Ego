const patterns=Object.entries(english).filter(([key])=>key.includes('{')).map(([key,value])=>{
  const names=[];
  const source=key.split(/(\{\w+\})/g).map(part=>{
    if(/^\{\w+\}$/.test(part)){names.push(part.slice(1,-1));return '([\\s\\S]*?)';}
    return part.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
  }).join('');
  return {regexp:new RegExp(`^${source}$`),names,value};
});
export function translate(language,text,values={}){
  const original=String(text??'');
  const fill=(template,params)=>template.replace(/\{(\w+)\}/g,(token,key)=>params[key]??token);
  if(language!=='en')return fill(original,values);
  if(english[original])return fill(english[original],values);
  for(const {regexp,names,value} of patterns){
    const match=original.match(regexp);
    if(match)return fill(value,Object.fromEntries(names.map((name,i)=>[name,match[i+1]])));
  }
  return fill(original,values);
}
