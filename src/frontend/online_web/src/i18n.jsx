// These templates originate in local validators and status formatters. Captured values
// (file names, IDs, counts and server details) are inserted verbatim.
const localMessageTemplates = [
  'Maximum {limit} characters.',
  'This update cannot exceed {limit} characters in total.',
  'The content exceeds the {limit}-character limit.',
  'Enter a page from 1 to {limit}.',
  'Only {count} {pages} currently available.',
  'Select no more than {count} media files.',
  '{file} is not a supported image or audio file.',
  '{file} is empty.',
  '{file} exceeds the 50 MiB limit.',
  '{file} has invalid dimensions.',
  'Rokid RTMP live ingest stopped. Showing latest frame preview: {detail}',
  'Active Rokid session API is unavailable: {detail}. Deploy and restart the backend with /rokid/stream/active first.',
  'Active Rokid RTMP session is stale or failed. Start recording on the Rokid Glass app again, then retry Rokid RTMP. {detail}',
  'Rokid API returned {mode}, not Rokid Glass',
  'Active Rokid session is {mode}, not Rokid RTMP. Start RTMP recording on the Rokid Glass app first.',
  'WHIP publish failed: {status} {detail}',
  'SDP answer invalid: {detail}'
].map((template) => {
  const names = []
  const parts = template.split(/(\{\w+\})/g).map((part) => {
    if (/^\{\w+\}$/.test(part)) {
      names.push(part.slice(1, -1))
      return '([\\s\\S]*?)'
    }
    return part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  })
  return { template, names, pattern: new RegExp('^' + parts.join('') + '$') }
})

function interpolate(text, params) {
  return text.replace(/\{(\w+)\}/g, (placeholder, name) => (
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : placeholder
  ))
}

export const LanguageContext = createContext({ language: 'en', t: (text, params = {}) => typeof text === 'string' ? interpolate(text, params) : text })
export function useLanguage() {
  return useContext(LanguageContext)
}
export function translateText(language, text, params = {}) {
  if (typeof text !== 'string') return text
  if (language !== 'zh') return interpolate(text, params)
  if (Object.prototype.hasOwnProperty.call(translations, text)) return interpolate(translations[text], params)
  // API formatters append diagnostic IDs to a local message. Translate only that
  // known prefix; keep all remaining diagnostic data untouched.
  const separator = text.indexOf(' · ')
  if (separator > 0 && Object.prototype.hasOwnProperty.call(translations, text.slice(0, separator))) {
    return translations[text.slice(0, separator)] + text.slice(separator)
      .replace('Request ID: ', '请求 ID：')
      .replace(/ Automatic checks paused\.$/, ' 自动检查已暂停。')
  }
  for (const { template, names, pattern } of localMessageTemplates) {
    const match = text.match(pattern)
    if (match) return interpolate(translations[template], Object.fromEntries(names.map((name, index) => [name, match[index + 1]])))
  }
  return text
}
